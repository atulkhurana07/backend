def seed():
    print("=" * 60)
    print("Seeding Authentic EV Charging Station Data for Jaipur & Cities")
    print("=" * 60)

    conn = psycopg2.connect(DATABASE_URL, connect_timeout=15)
    cur = conn.cursor(cursor_factory=RealDictCursor)

    now = datetime.now(timezone.utc)
    inserted_count = 0
    updated_count = 0

    for s in STATIONS_DATA:
        cur.execute("SELECT id FROM charging_centers WHERE name = %s;", (s["name"],))
        row = cur.fetchone()
        if row:
            cur.execute("""
                UPDATE charging_centers
                SET latitude = %s, longitude = %s, address = %s, city = %s, state = %s,
                    pincode = %s, status = %s, power_kw = %s, contact_phone = %s,
                    operating_hours = %s, description = %s, connectors = %s,
                    amenities = %s, source = %s, public_visible = %s, last_verified_at = %s,
                    updated_at = %s
                WHERE id = %s;
            """, (
                s["latitude"], s["longitude"], s["address"], s["city"], s["state"],
                s["pincode"], s["status"], s["power_kw"], s["contact_phone"],
                s["operating_hours"], s["description"], Json(s["connectors"]),
                Json(s["amenities"]), s["source"], s["public_visible"], now,
                now, row["id"]
            ))
            updated_count += 1
        else:
            new_id = str(uuid.uuid4())
            cur.execute("""
                INSERT INTO charging_centers (
                    id, name, latitude, longitude, address, city, state, pincode,
                    status, power_kw, contact_phone, operating_hours, description,
                    connectors, amenities, source, public_visible, last_verified_at,
                    created_at, updated_at
                ) VALUES (
                    %s, %s, %s, %s, %s, %s, %s, %s,
                    %s, %s, %s, %s, %s,
                    %s, %s, %s, %s, %s,
                    %s, %s
                );
            """, (
                new_id, s["name"], s["latitude"], s["longitude"], s["address"], s["city"], s["state"], s["pincode"],
                s["status"], s["power_kw"], s["contact_phone"], s["operating_hours"], s["description"],
                Json(s["connectors"]), Json(s["amenities"]), s["source"], s["public_visible"], now,
                now, now
            ))
            inserted_count += 1

    conn.commit()
    print(f"[+] Successfully inserted {inserted_count} new charging stations!")
    print(f"[+] Successfully updated {updated_count} existing charging stations!")

    # Verify counts per city
    cur.execute("SELECT city, count(*) as count FROM charging_centers GROUP BY city ORDER BY count DESC;")
    summary = cur.fetchall()
    print("\n--- Current Charging Centers in Database by City ---")
    for r in summary:
        print(f"  {r['city'] or 'UNKNOWN'}: {r['count']} stations")

    cur.close()
    conn.close()
    print("=" * 60)
    print("Seeding completed successfully.")

